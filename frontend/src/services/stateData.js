// Helper to get nearest airports for any state slug
export const getAirportsForState = (slug) => {
  const normSlug = slug ? slug.toLowerCase().trim() : "";
  if (INDIAN_STATE_AIRPORTS[normSlug]) {
    return INDIAN_STATE_AIRPORTS[normSlug];
  }
  const formattedName = normSlug
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());
  return [
    { name: `${formattedName} Domestic Airport`, code: formattedName.substring(0, 3).toUpperCase(), city: formattedName },
    { name: "Regional Connecting Airport", code: "IND", city: "Regional Hub" }
  ];
};

